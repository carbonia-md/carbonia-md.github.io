/** Denylist terms for a place name: the full name plus its no-space form. */
export function denylistTerms(name) {
  const full = name.toLowerCase().trim();
  const collapsed = full.replace(/\s+/g, '');
  return [...new Set([full, collapsed])].filter(Boolean);
}

/* ── The write pass ──────────────────────────────────────────────────────── */

/**
 * Writes all adoption artifacts under `root`. Returns a log of actions taken
 * (one string per artifact) for the transcript.
 */
export function writeInstance(root, cfg) {
  const actions = [];
  const write = (rel, content) => {
    writeFileSync(join(root, rel), content);
    actions.push(`wrote   ${rel}`);
  };

  // place.config.ts — the single writer. The type declaration is read out of the
  // file about to be overwritten, so the wizard emits the framework's own
  // declaration rather than a copy that can drift from it (ADR: none; the copy
  // this replaces had lost five keys). Read BEFORE the write, and fail loudly:
  // a config emitted with no type at all is worse than no config.
  const configPath = join(root, 'place.config.ts');
  let interfaceBlock;
  try {
    interfaceBlock = extractInterfaceBlock(readFileSync(configPath, 'utf8'));
  } catch (e) {
    throw new Error(
      `cannot derive the PlaceConfig declaration from ${configPath}: ${e.message}. ` +
        'The wizard re-emits the committed declaration instead of carrying its own ' +
        'copy, so place.config.ts must be present and carry exactly one.',
    );
  }
  write('place.config.ts', renderPlaceConfig(cfg, interfaceBlock));

  // knowledge/: remove demo content, reseed category dirs + INBOX.md.
  rmSync(join(root, 'knowledge'), { recursive: true, force: true });
  for (const cat of cfg.categories) {
    const dir = join(root, 'knowledge', cat.title);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, '.gitkeep'), '');
  }
  actions.push(
    `seeded  knowledge/{${cfg.categories.map((c) => c.title).join(',')}}/`,
  );
  write('knowledge/INBOX.md', INBOX_MD);

  // Demo media: the synthesized soundscape clips are demo content, removed the
  // same way the demo articles are. Their manifest went with the knowledge/
  // reseed above, so an adopted instance starts with neither, and /soundscape
  // renders its documented empty state until the adopter ships their own audio.
  const removedMedia = [];
  for (const rel of DEMO_MEDIA) {
    const path = join(root, rel);
    if (!existsSync(path)) continue;
    rmSync(path, { recursive: true, force: true });
    removedMedia.push(rel);
  }
  if (removedMedia.length > 0) {
    actions.push(`removed ${removedMedia.join(', ')} (demo media)`);
  }

  // CNAME: custom domain only. GitHub Pages default domains must not have one.
  const cname = join(root, 'CNAME');
  if (cfg.place.domain.toLowerCase().endsWith('.github.io')) {
    if (existsSync(cname)) {
      unlinkSync(cname);
      actions.push('removed CNAME (*.github.io domain)');
    } else {
      actions.push('skipped CNAME (*.github.io domain)');
    }
  } else {
    write('CNAME', `${cfg.place.domain}\n`);
  }

  // AGENTS.md: the instance's agent-instruction SSOT (place identity + content
  // working set), regenerated place-specifically. Overwrites the framework
  // starter (which carries the demo place + the dev-plugin sentinel block);
  // instance-owned (merge=ours) so upgrades never clobber it afterward. A fresh
  // instance ships zero dev-plugin state — renderAgentsMd emits no sentinel block.
  write('AGENTS.md', renderAgentsMd(cfg));

  // CLAUDE.md: a one-line `@AGENTS.md` shim. Claude Code inlines it recursively
  // to reach AGENTS.md; no place content of its own to drift.
  write('CLAUDE.md', CLAUDE_MD_SHIM);

  // README.md: the instance repo front page (replaces the template's README).
  write('README.md', renderReadme(cfg));

  // CHANGELOG.md: replace the framework release log with instance-only history.
  // It is protected by merge=ours, while /sekai-upgrade reads future framework notes
  // directly from the immutable target tag.
  write('CHANGELOG.md', renderChangelog(cfg));

  // package.json/package-lock.json: package identity belongs to the adopter;
  // scripts and dependency contracts remain framework-owned. package versions
  // mirror the adopter's VERSION without its leading v.
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  pkg.name = slugify(cfg.place.name);
  pkg.private = true;
  pkg.description = `AI-native open knowledge base for ${cfg.place.name}.`;
  pkg.version = '0.0.0';
  write('package.json', `${JSON.stringify(pkg, null, 2)}\n`);

  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
  lock.name = pkg.name;
  lock.version = pkg.version;
  lock.packages[''].name = pkg.name;
  lock.packages[''].version = pkg.version;
  write('package-lock.json', `${JSON.stringify(lock, null, 2)}\n`);

  // VERSION is the adopter's own release SSOT. FRAMEWORK-VERSION is the exact
  // sekai-kb release adopted by this checkout. The template carries only the
  // latter; init creates VERSION and preserves the framework value.
  write('VERSION', 'v0.0.0\n');
  const frameworkVersion = readFileSync(join(root, 'FRAMEWORK-VERSION'), 'utf8').trim();
  write('FRAMEWORK-VERSION', `${frameworkVersion}\n`);

  // Local genericity denylist: create or append (idempotent per term). The
  // framework denylist file is never touched.
  const localRel = 'scripts/ci/genericity-denylist.local.txt';
  const localPath = join(root, localRel);
  const existing = existsSync(localPath) ? readFileSync(localPath, 'utf8') : null;
  const have = new Set(
    (existing ?? '')
      .split('\n')
      .map((l) => l.trim())
      .filter((l) => l && !l.startsWith('#')),
  );
  const missing = denylistTerms(cfg.place.name).filter((t) => !have.has(t));
  if (existing === null) {
    write(localRel, `${DENYLIST_LOCAL_HEADER}${missing.join('\n')}\n`);
  } else if (missing.length > 0) {
    const sep = existing.endsWith('\n') ? '' : '\n';
    writeFileSync(localPath, `${existing}${sep}${missing.join('\n')}\n`);
    actions.push(`appended ${localRel} (+${missing.length} term(s))`);
  } else {
    actions.push(`kept    ${localRel} (terms already present)`);
  }

  // Template → instance: drop the marker so the gates scan code trees only.
  const marker = join(root, '.sekai-template');
  if (existsSync(marker)) {
    unlinkSync(marker);
    actions.push('removed .sekai-template (instance mode)');
  }

  // Dev-plugin strip: the framework's own dev-workflow state (config + engineering
  // rules under .agent-toolkit/) is framework-development state, never adopter
  // content. A fresh instance ships zero dev-plugin state; an adopter who wants the
  // dev workflow runs `dev:setup` to create their own. Remove the tree here;
  // check-init.sh asserts it is absent post-init. The AGENTS.md dev-plugin sentinel
  // block needs no separate strip: renderAgentsMd (above) rewrites AGENTS.md without
  // it, so the freshly written instance file carries no dev-plugin reference.
  //
  // The two removals together are the `stripped` dev-plugin state that every later
  // framework upgrade must preserve. `merge=ours` cannot protect a deleted path, so
  // /sekai-upgrade classifies this state before merging and reconciles it after
  // (scripts/upgrade/dev-plugin-state.mjs, ADR 006 addendum); do not change what is
  // removed here without updating that helper's definition of `stripped`.
  const agentToolkit = join(root, '.agent-toolkit');
  if (existsSync(agentToolkit)) {
    rmSync(agentToolkit, { recursive: true, force: true });
    actions.push('removed .agent-toolkit/ (dev-plugin state not shipped to adopters)');
  }

  // Maintainer-doc strip (ADR 008): same reasoning as the dev-plugin strip above —
  // framework-development state, removed so a fresh instance carries only the docs it
  // operates with. docs/playbook/ and docs/runbook/ are untouched by construction:
  // they are not in MAINTAINER_DOCS. Each path is removed only when present, so the
  // wizard stays runnable on a tree that already lacks them.
  const removedDocs = [];
  for (const rel of MAINTAINER_DOCS) {
    const path = join(root, rel);
    if (!existsSync(path)) continue;
    rmSync(path, { recursive: true, force: true });
    removedDocs.push(rel);
  }
  if (removedDocs.length > 0) {
    actions.push(`removed ${removedDocs.join(', ')} (framework maintainer docs)`);
  }

  return actions;
}
